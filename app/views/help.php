        <!-- ETAPA 4 -->
        <h3>Etapa 4: Gerenciando o Carrinho de Compras</h3>
        <p>No painel <strong>"Produtos Adicionados"</strong>, você pode revisar e ajustar toda a compra antes de finalizar:</p>

        <p><strong>Alterar Quantidades:</strong> Toque no botão de mais (<code>+</code>) ou menos (<code>-</code>) ao lado de cada item para ajustar o volume desejado. O subtotal do produto se atualizará sozinho.</p>
        <p><strong>Preços Promocionais:</strong> Itens com ofertas ativas exibirão o valor final em cor azul (destaque promocional).</p>
        <p><strong>Excluir Itens:</strong> Se quiser remover um produto adicionado incorretamente, basta tocar no ícone da lixeira ao lado do valor dele.</p>
        <p><strong>Acompanhar o Valor Total:</strong> No rodapé da tela, o painel de cor cinza exibe de maneira contínua o valor total somado da compra.</p>
        <p><strong>Mais Itens:</strong> Para voltar e adicionar mais produtos, toque no botão azul de adição rápida (com o símbolo <code>+</code>) localizado no rodapé direito.</p>

