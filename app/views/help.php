    <h2 id="installation">Instalação do App</h2>
    <h3>Android - Google Chrome</h3>
    <p>Toque nos três pontinhos (menu) localizados no canto superior direito do Google Chrome. Procure e toque na opção "Instalar aplicativo" (ou "Adicionar à tela inicial"). Confirme a ação tocando em "Instalar". O ícone do aplicativo será criado na tela inicial do seu celular.</p>
    <h3>iPhone - Google Chrome</h3>
    <p>Localize e toque no botão de Compartilhar (ícone de um quadrado com uma seta apontando para cima) na barra do Chrome. No painel que subir na tela, role as opções e toque em "Adicionar à Tela de Início". Confirme tocando em "Adicionar" no canto superior direito.</p>  
