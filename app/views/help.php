        <h3>Etapa 3: Adicionando Produtos (Câmera ou Manual)</h3>
        <p>O aplicativo oferece duas maneiras práticas de buscar e inserir os itens no carrinho de compras:</p>

        <p><strong>Opção A: Usando a Câmera do Celular (Código de Barras)</strong></p>
