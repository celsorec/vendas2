    <!-- ETAPA 2 -->
    <h3>Etapa 2: Como Iniciar uma Venda</h3>
    <p>A tela inicial é simples e direta para agilizar o início do seu atendimento diário:</p>
    <p>No topo da tela você verá uma mensagem de boas-vidas com o seu nome.</p>
    <p>Para iniciar o registro de uma nova venda, basta clicar no botão azul central escrito <strong>"Adicionar Produto"</strong>.</p>

    <figure>
        <img src="app/media/images/home.png" alt="Tela inicial">
        <figcaption>Tela inicial</figcaption>
    </figure>
    <hr>

    <!-- ETAPA 3 -->
    <h3>Etapa 3: Adicionando Produtos (Câmera ou Manual)</h3>
    <p>O aplicativo oferece duas maneiras práticas de buscar e inserir os itens no carrinho de compras:</p>

    <p><strong>Opção A: Usando a Câmera do Celular (Código de Barras)</strong></p>
    <p>Ao clicar em adicionar produto, a câmera traseira do seu dispositivo se abrirá automaticamente.</p>
    <p>Aproxime e centralize o código de barras da etiqueta do produto dentro da área indicada na tela.</p>
    <p>Assim que o código for reconhecido, o item será incluído diretamente na sua lista de compras e você será levado para o carrinho.</p>

    <figure>
        <img src="app/media/images/barcode.png" alt="Leitura do código de barras">
        <figcaption>Leitura do código de barras</figcaption>
    </figure>
    <br>

    <p><strong>Opção B: Digitação Manual</strong></p>
    <p>Caso a câmera apresente dificuldades de leitura ou você prefira digitar, clique em <strong>"INSERIR MANUALMENTE"</strong> na tela de leitura.</p>
    <p>Insira o código numérico de barras do produto e clique no resultado exibido logo abaixo para adicioná-lo.</p>

    <figure>
        <img src="app/media/images/search.png" alt="Buscando produtos manualmente">
        <figcaption>Buscando produtos manualmente</figcaption>
    </figure>
    <hr>

    <!-- ETAPA 4 -->
    <h3>Etapa 4: Gerenciando o Carrinho de Compras</h3>
    <p>No painel <strong>"Produtos Adicionados"</strong>, você pode revisar e ajustar toda a compra antes de finalizar:</p>

    <p><strong>Alterar Quantidades:</strong> Toque no botão de mais (<code>+</code>) ou menos (<code>-</code>) ao lado de cada item para ajustar o volume desejado. O subtotal do produto se atualizará sozinho.</p>
    <p><strong>Preços Promocionais:</strong> Itens com ofertas ativas exibirão o valor final em destaque promocional.</p>
    <p><strong>Excluir Itens:</strong> Se quiser remover um produto adicionado incorretamente, basta tocar no ícone da lixeira ao lado do valor dele.</p>
    <p><strong>Acompanhar o Valor Total:</strong> No rodapé da tela, o painel exibe de maneira contínua o valor total somado da compra.</p>
    <p><strong>Mais Itens:</strong> Para voltar e adicionar mais produtos, toque no botão azul de adição rápida localizado no rodapé direito.</p>

    <figure>
        <img src="app/media/images/cart.png" alt="Carrinho de compras">
        <figcaption>Carrinho de compras</figcaption>
    </figure>
    <hr>

    <!-- ETAPA 5 -->
    <h3>Etapa 5: Finalizando a Venda (Checkout)</h3>
    <p>Com o carrinho preenchido, toque no botão verde com ícone de <strong>Cédula de Dinheiro</strong> no canto inferior direito para abrir as opções de pagamento:</p>

    <p><strong>Forma de Pagamento:</strong> Escolha a opção desejada na listagem de métodos de pagamento disponíveis (como Dinheiro, Cartões ou A Prazo).</p>
    <p><strong>Localizar Cliente:</strong> No campo "Cliente", digite o código do cliente cadastrado. Clique no nome dele assim que aparecer nos resultados de busca para vinculá-lo à venda. A seleção do cliente é obrigatória para as modalidades <strong>"A prazo"</strong> ou <strong>"Cartão Fidelidade"</strong>.</p>

    <p><strong>Descontos (Percentual ou Valor Fixo):</strong></p>
    <p>Digite o percentual de desconto desejado ou insira diretamente o valor final negociado com o cliente. Caso você conceda um desconto maior do que o seu limite autorizado pelo sistema, a janela de <strong>"Senha de Autorização"</strong> surgirá. Solicite que o gerente insira a credencial de liberação para prosseguir.</p>

    <p><strong>Parcelamento e Entrada:</strong></p>
    <p>Se a venda tiver uma entrada em dinheiro, digite o valor correspondente para recalcular o saldo restante. Insira a quantidade de prestações desejada no campo correspondente para obter o valor exato de cada parcela mensal.</p>
    <p><strong>Conclusão da Venda:</strong> Para finalizar, revise as informações e clique no botão verde <strong>"Concluir Venda"</strong> no rodapé.</p>

    <figure>
        <img src="app/media/images/checkout.png" alt="Checkout">
        <figcaption>Checkout</figcaption>
    </figure>
    <hr>

    <!-- ETAPA 6 -->
    <h3>Etapa 6: Emissão do Comprovante</h3>
    <p>Ao concluir a venda, os dados salvos em seu dispositivo serão limpos para a próxima operação, e o sistema fará a impressão do comprovante de vendas na impressora configurada na rede local.</p> 
