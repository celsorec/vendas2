        <h2 id="installation">Instalação do App</h2>
        <h3>Android - Google Chrome</h3>
        <p>Toque nos três pontinhos (menu) localizados no canto superior direito do Google Chrome. Procure e toque na opção "Instalar aplicativo" (ou "Adicionar à tela inicial"). Confirme a instalação: Na janela de confirmação que se abrirá na tela, toque em "Instalar" (ou "Adicionar"). Pronto! Agora, basta ir para a tela de aplicativos do seu celular para encontrar o ícone do Vendas 2.0.</p>
        <h3>iPhone - Google Chrome</h3>
        <p>Abra o menu de compartilhamento: Na barra superior do Chrome, localize e toque no botão de Compartilhar (aquele ícone que se parece com um quadrado com uma seta apontando para cima). Adicione à tela de início: No painel de opções que subirá na tela, clique em 'Ver Mais', role as opções um pouco para baixo até encontrar e tocar em "Adicionar à Tela de Início" (ícone de um sinal de mais + dentro de um quadrado). Confirme e adicione: Toque no botão "Adicionar", localizado no canto superior direito da tela. Pronto! O aplicativo será adicionado à tela inicial do seu iPhone como se fosse um aplicativo baixado diretamente da App Store.</p>
