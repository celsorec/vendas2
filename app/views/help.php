        <p><strong>Selecione a Loja:</strong> Toque no logotipo correspondente à sua bandeira (<em>Ideal Magazine</em>, <em>Maruzi</em> ou <em>Ideal Sports</em>).</p>
        <p><strong>Selecione a Localização:</strong> No menu de opções, escolha a cidade ou filial física onde você está operando.</p>
        <p><strong>Informe seu Código:</strong> Digite o seu número de identificação de vendedor exclusivo no campo indicado.</p>
        <p><strong>Entrar:</strong> Clique no botão <strong>"Prosseguir"</strong> para acessar a tela inicial de vendas.</p>

